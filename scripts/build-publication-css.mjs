import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import tailwindcss from "@tailwindcss/postcss";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const input = path.join(root, "src", "styles", "publication-runtime.css");
const output = path.join(root, "public", "publication-runtime.css");

const source = readFileSync(input, "utf8");
const result = await postcss([tailwindcss()]).process(source, {
  from: input,
  to: output,
});

mkdirSync(path.dirname(output), { recursive: true });
writeFileSync(
  output,
  `/* generated by scripts/build-publication-css.mjs */\n${result.css}`,
);
console.log(
  `Wrote ${path.relative(root, output)} (${result.css.length} bytes)`,
);
